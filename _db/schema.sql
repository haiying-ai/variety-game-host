-- ------------------------------------------------------------
-- 1. 表结构
-- ------------------------------------------------------------

-- 综艺：《现在就出发》《奔跑吧》…
CREATE TABLE IF NOT EXISTS shows (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text        NOT NULL UNIQUE,
  emoji       text        NOT NULL DEFAULT '🎬',
  description text        NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- 期数：某综艺的某一季某一期
CREATE TABLE IF NOT EXISTS episodes (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  show_id    bigint      NOT NULL REFERENCES shows(id) ON DELETE CASCADE,
  season     integer     NOT NULL,
  episode_no integer     NOT NULL,
  title      text        NOT NULL DEFAULT '',
  aired_on   date,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT episodes_uniq_ep UNIQUE (show_id, season, episode_no)
);

-- 游戏：一期里的一个可玩玩法
--   play_style 是宽松字符串（words / char / song / sentence / werewolf /
--   boss / number / truthdare / undercover…），客户端会结合 name 与
--   word_pool 结构做二次归类，因此这里不加枚举约束。
--   word_pool 的形状随玩法变化，常见键：words / chars / songs / sentences /
--   scenes / poses / challenges / traps / signals / hint / boss / pairs。
CREATE TABLE IF NOT EXISTS games (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  episode_id  bigint      NOT NULL REFERENCES episodes(id) ON DELETE CASCADE,
  name        text        NOT NULL,
  play_style  text        NOT NULL DEFAULT '',
  rules       text        NOT NULL DEFAULT '',
  tags        text[]      NOT NULL DEFAULT '{}',
  min_players integer     NOT NULL DEFAULT 2,
  max_players integer     NOT NULL DEFAULT 20,
  need_props  text        NOT NULL DEFAULT '无',
  word_pool   jsonb       NOT NULL DEFAULT '{}'::jsonb,
  scene       text        NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT games_uniq_ep_name UNIQUE (episode_id, name)
);

-- 待入库队列：采集侧写入，客户端消费
CREATE TABLE IF NOT EXISTS remote_feed (
  id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  show_name    text        NOT NULL,
  season       integer     NOT NULL,
  episode_no   integer     NOT NULL,
  title        text,
  aired_on     date,
  payload      jsonb,
  ingested     boolean     NOT NULL DEFAULT false,
  ingest_error text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT remote_feed_uniq_ep UNIQUE (show_name, season, episode_no)
);

-- 同步状态：全库只有 id = 'global' 这一行
CREATE TABLE IF NOT EXISTS sync_state (
  id           text PRIMARY KEY DEFAULT 'global',
  data_version bigint      NOT NULL DEFAULT 0,
  last_sync_at timestamptz,
  last_result  text,
  last_error   text,
  lock_owner   text,
  lock_at      timestamptz
);

INSERT INTO sync_state (id) VALUES ('global') ON CONFLICT (id) DO NOTHING;

-- ------------------------------------------------------------
-- 2. 索引
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS games_episode_id_idx    ON games (episode_id);
CREATE INDEX IF NOT EXISTS episodes_show_id_idx    ON episodes (show_id);
CREATE INDEX IF NOT EXISTS remote_feed_pending_idx ON remote_feed (season DESC, episode_no DESC)
  WHERE ingested = false;

-- ------------------------------------------------------------
-- 3. RPC 函数
--    全部 SECURITY DEFINER：客户端不直接写表，只调这些函数。
-- ------------------------------------------------------------

-- 3.1 抢同步锁：原子判断 + 占用，只有一个客户端能拿到
--     p_lease 为租约时长，超过即视为上次进程已崩溃，可被重新抢占。
CREATE OR REPLACE FUNCTION public.try_claim_sync(
  p_owner text,
  p_lease interval DEFAULT '10 minutes'
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_rows integer;
BEGIN
  UPDATE sync_state
     SET lock_owner = p_owner,
         lock_at    = now()
   WHERE id = 'global'
     AND (lock_owner IS NULL OR lock_at IS NULL OR lock_at < now() - p_lease);

  GET DIAGNOSTICS v_rows = ROW_COUNT;
  RETURN v_rows > 0;
END;
$$;

-- 3.2 单条 feed 原子入库：一条记录一个事务，幂等、毒丸免疫
CREATE OR REPLACE FUNCTION public.ingest_feed_row(p_row_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row         remote_feed%ROWTYPE;
  v_show_id     bigint;
  v_ep_id       bigint;
  v_created_ep  boolean := false;
  v_g           jsonb;
  v_tags        text[];
  v_pool        jsonb;
  v_is_identity boolean;
  v_inserted    integer := 0;
  v_skipped     integer := 0;
BEGIN
  SELECT * INTO v_row FROM remote_feed WHERE id = p_row_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 'missing');
  END IF;
  IF v_row.ingested THEN
    RETURN jsonb_build_object('status', 'already');
  END IF;
  IF v_row.payload IS NULL
     OR jsonb_typeof(v_row.payload) <> 'array'
     OR jsonb_array_length(v_row.payload) = 0 THEN
    UPDATE remote_feed SET ingested = true, ingest_error = 'payload为空或不是数组' WHERE id = p_row_id;
    RETURN jsonb_build_object('status', 'empty');
  END IF;

  SELECT id INTO v_show_id FROM shows WHERE name = v_row.show_name;
  IF v_show_id IS NULL THEN
    INSERT INTO shows(name, emoji, description)
    VALUES (v_row.show_name, '🎬', '最新更新')
    RETURNING id INTO v_show_id;
  END IF;

  SELECT id INTO v_ep_id FROM episodes
   WHERE show_id = v_show_id AND season = v_row.season AND episode_no = v_row.episode_no;
  IF v_ep_id IS NULL THEN
    INSERT INTO episodes(show_id, season, episode_no, title, aired_on)
    VALUES (v_show_id, v_row.season, v_row.episode_no,
            COALESCE(v_row.title, '第' || v_row.episode_no || '期'), v_row.aired_on)
    RETURNING id INTO v_ep_id;
    v_created_ep := true;
  END IF;

  FOR v_g IN SELECT * FROM jsonb_array_elements(v_row.payload) LOOP
    IF v_g->>'name' IS NULL OR btrim(v_g->>'name') = ''
       OR btrim(COALESCE(v_g->>'rules', '')) = '' THEN
      v_skipped := v_skipped + 1;
      CONTINUE;
    END IF;
    IF EXISTS (SELECT 1 FROM games WHERE episode_id = v_ep_id AND name = v_g->>'name') THEN
      v_skipped := v_skipped + 1;
      CONTINUE;
    END IF;

    -- 标签白名单 + 互斥规则
    v_tags := ARRAY(SELECT t FROM jsonb_array_elements_text(COALESCE(v_g->'tags', '[]'::jsonb)) t
                     WHERE t IN ('分组', '场地', '坐玩', '动作', '狼人杀', '积分'));
    IF '场地' = ANY(v_tags) AND '坐玩' = ANY(v_tags) THEN
      v_tags := array_remove(v_tags, '坐玩');
    END IF;

    -- 身份类玩法必须带「狼人杀」标签
    v_pool := COALESCE(v_g->'word_pool', '{}'::jsonb);
    v_is_identity := (COALESCE(v_pool->>'hint', '') LIKE '%角色%')
      OR (jsonb_typeof(v_pool->'signals') = 'array' AND jsonb_array_length(v_pool->'signals') > 0)
      OR (v_pool ? 'boss');
    IF v_is_identity AND NOT ('狼人杀' = ANY(v_tags)) THEN
      v_tags := array_append(v_tags, '狼人杀');
    END IF;

    INSERT INTO games(episode_id, name, play_style, rules, tags,
                      min_players, max_players, need_props, word_pool, scene)
    VALUES (
      v_ep_id,
      btrim(v_g->>'name'),
      COALESCE(v_g->>'play_style', ''),
      replace(COALESCE(v_g->>'rules', ''), E'\\n', chr(10)),
      v_tags,
      CASE WHEN COALESCE(v_g->>'min_players', '') ~ '^[0-9]+$' THEN (v_g->>'min_players')::int ELSE 2 END,
      CASE WHEN COALESCE(v_g->>'max_players', '') ~ '^[0-9]+$' THEN (v_g->>'max_players')::int ELSE 20 END,
      COALESCE(v_g->>'need_props', '无'),
      v_pool,
      COALESCE(v_g->>'scene', '')
    );
    v_inserted := v_inserted + 1;
  END LOOP;

  UPDATE remote_feed SET ingested = true, ingest_error = NULL WHERE id = p_row_id;

  RETURN jsonb_build_object(
    'status', 'ok',
    'games', v_inserted,
    'skipped', v_skipped,
    'episode_created', v_created_ep,
    'episode_id', v_ep_id
  );
END;
$$;

-- 3.3 毒丸标记：单条坏数据跳过，永不阻塞队列
CREATE OR REPLACE FUNCTION public.mark_feed_failed(p_row_id bigint, p_error text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE remote_feed
     SET ingested = true,
         ingest_error = left(p_error, 500)
   WHERE id = p_row_id;
END;
$$;

-- 3.4 原子释放锁：解锁 + 时间戳 + 版本自增 + 结果留痕，一步完成
CREATE OR REPLACE FUNCTION public.release_sync(
  p_owner text,
  p_bumped boolean,
  p_result text,
  p_error text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE sync_state
     SET lock_owner   = NULL,
         lock_at      = NULL,
         last_sync_at = now(),
         last_result  = p_result,
         last_error   = p_error,
         data_version = CASE WHEN p_bumped THEN data_version + 1 ELSE data_version END
   WHERE id = 'global' AND lock_owner = p_owner;
END;
$$;

-- ------------------------------------------------------------
-- 4. 行级权限：客户端对小程序的正式表只读，写操作只能走上面的函数
-- ------------------------------------------------------------

ALTER TABLE shows       ENABLE ROW LEVEL SECURITY;
ALTER TABLE episodes    ENABLE ROW LEVEL SECURITY;
ALTER TABLE games       ENABLE ROW LEVEL SECURITY;
ALTER TABLE sync_state  ENABLE ROW LEVEL SECURITY;
ALTER TABLE remote_feed ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS shows_all       ON shows;
DROP POLICY IF EXISTS episodes_all    ON episodes;
DROP POLICY IF EXISTS games_all       ON games;
DROP POLICY IF EXISTS sync_state_all  ON sync_state;
DROP POLICY IF EXISTS remote_feed_all ON remote_feed;

-- 策略分两种写法：实例存在 anon / authenticated 角色时按角色授权（Supabase
-- 风格）；否则退化为对所有角色可读，效果等价且不会因角色不存在而报错。
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['shows', 'episodes', 'games', 'sync_state', 'remote_feed'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE format('CREATE POLICY %I ON %I FOR SELECT TO anon, authenticated USING (true)',
                     t || '_read', t);
    ELSE
      EXECUTE format('CREATE POLICY %I ON %I FOR SELECT USING (true)', t || '_read', t);
    END IF;
  END LOOP;
END;
$$;

-- 角色授权：anon / authenticated 是 Supabase 风格的默认角色名。
-- 若你的实例没有这两个角色，下面的 DO 块会直接跳过，不影响建表。
DO $$
DECLARE
  r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('GRANT USAGE ON SCHEMA public TO %I', r);
      EXECUTE format('GRANT SELECT ON shows, episodes, games, sync_state, remote_feed TO %I', r);
      EXECUTE format('GRANT EXECUTE ON FUNCTION public.try_claim_sync(text, interval) TO %I', r);
      EXECUTE format('GRANT EXECUTE ON FUNCTION public.ingest_feed_row(bigint) TO %I', r);
      EXECUTE format('GRANT EXECUTE ON FUNCTION public.mark_feed_failed(bigint, text) TO %I', r);
      EXECUTE format('GRANT EXECUTE ON FUNCTION public.release_sync(text, boolean, text, text) TO %I', r);
    END IF;
  END LOOP;
END;
$$;

